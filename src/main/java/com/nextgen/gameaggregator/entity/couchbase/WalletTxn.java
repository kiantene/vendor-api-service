package com.nextgen.gameaggregator.entity.couchbase;

import com.fasterxml.jackson.annotation.JsonIgnore;
import com.fasterxml.jackson.annotation.JsonProperty;
import com.fasterxml.jackson.annotation.JsonSubTypes;
import com.fasterxml.jackson.annotation.JsonTypeInfo;
import com.fasterxml.jackson.databind.annotation.JsonDeserialize;
import com.fasterxml.jackson.databind.annotation.JsonSerialize;
import com.fasterxml.jackson.databind.deser.std.NumberDeserializers;
import com.fasterxml.jackson.databind.ser.std.ToStringSerializer;
import com.nextgen.core.util.UuidUtil;
import com.nextgen.gameaggregator.enums.GameRoundState;
import com.nextgen.gameaggregator.enums.TxnStatus;
import lombok.Data;

import java.math.BigDecimal;
import java.time.Instant;
import java.time.ZoneOffset;
import java.time.format.DateTimeFormatter;

/**
 * Shared audit-header for wallet-movement Couchbase entities ({@link DebitTxn}, {@link CreditTxn})
 * issued by vendors that speak debit/credit on the wire.
 *
 * <p><strong>Independent of {@link RoundTxn}.</strong> The debit/credit framework is a parallel
 * world to the legacy BET/RESULT/ROLLBACK pipeline — different doc collection
 * ({@code wallet_round_transactions}), different round model ({@link WalletRoundLedger}),
 * different lifecycle. {@code WalletTxn} owns its own polymorphic discriminator
 * ({@code kind} property; DEBIT or CREDIT) so reads via this parent resolve to the right leaf.
 *
 * <p>Field-name convention:
 * <ul>
 *   <li>{@code vendor*} — received from the vendor wire (pre-FX amounts, vendor-native ids/times).</li>
 *   <li>{@code ga*}     — generated by GA platform ({@link #gaTxnId} UUIDv7).</li>
 *   <li>{@code agent*}  — derived from agent/platform-side metadata ({@link #agentCurrency}, post-FX).</li>
 *   <li>no prefix       — pure platform-internal state ({@link #status}, {@link #state}, {@link #idx}, etc.).</li>
 * </ul>
 *
 * <p>Lifecycle fields ({@link #status}, {@link #state}) reuse the platform-wide
 * {@link TxnStatus} and {@link GameRoundState} enums respectively — they're enum vocabularies,
 * not BET-specific framework types.
 */
@Data
@JsonTypeInfo(
        use = JsonTypeInfo.Id.NAME,
        property = "kind"
)
@JsonSubTypes({
        @JsonSubTypes.Type(value = DebitTxn.class, name = "DEBIT"),
        @JsonSubTypes.Type(value = CreditTxn.class, name = "CREDIT")
})
public abstract class WalletTxn {
    private static final DateTimeFormatter DATE_TIME_FORMATTER = DateTimeFormatter
            .ofPattern("yyyy-MM-dd HH:mm:ss.SSS")
            .withZone(ZoneOffset.UTC);

    // --- Audit header ---

    /** Vendor's transaction id verbatim from the wire. Drives doc-id uniqueness + idempotency. */
    @JsonProperty("vendorTxnId")
    private String vendorTxnId;

    /** GA-generated UUIDv7. Sent to the operator as {@code transactionId}. */
    @JsonProperty("gaTxnId")
    private String gaTxnId;

    @JsonProperty("createdAt")
    private String createdAt;

    @JsonProperty("vendorClassName")
    private String vendorClassName;

    @JsonProperty("idx")
    private Integer idx;

    @JsonProperty("vendorId")
    private Integer vendorId;

    @JsonProperty("vendorRoundId")
    private String vendorRoundId;

    @JsonProperty("vendorPlayerUsername")
    private String vendorPlayerUsername;

    @JsonProperty("vendorGameCode")
    private String vendorGameCode;

    /** Agent/platform-side currency (post-FX), used by the operator wallet. NOT vendor currency. */
    @JsonProperty("agentCurrency")
    private String agentCurrency;

    /** Wallet-movement amount in vendor currency (pre-FX), always positive. */
    @JsonProperty("vendorAmount")
    @JsonSerialize(using = ToStringSerializer.class)
    @JsonDeserialize(using = NumberDeserializers.BigDecimalDeserializer.class)
    private BigDecimal vendorAmount;

    /** Vendor-facing balance after this txn (post-FX via {@code toVendorRate}). Mirrors {@code GameRound.lastBalance} semantics. */
    @JsonProperty("vendorBalance")
    @JsonSerialize(using = ToStringSerializer.class)
    @JsonDeserialize(using = NumberDeserializers.BigDecimalDeserializer.class)
    private BigDecimal vendorBalance;

    @JsonProperty("vendorBetTime")
    private Long vendorBetTime;

    @JsonProperty("createdTs")
    private Long createdTs;

    // --- Lifecycle state ---

    /** Reference-state lifecycle (see {@link DebitTxn} doc). {@link GameRoundState#UNSETTLED} → SETTLED / REFUNDED. */
    @JsonProperty("state")
    protected GameRoundState state = GameRoundState.UNSETTLED;

    /** Operator-call transport progress: NEW → SENT → SUCCESS / ERROR. */
    @JsonProperty("status")
    protected TxnStatus status = TxnStatus.NEW;

    @JsonProperty("exception")
    protected String exception;

    @JsonProperty("sentAt")
    protected String sentAt;

    @JsonProperty("doneAt")
    protected String doneAt;

    /**
     * Initialize the shared audit-header fields. Called by leaf factories
     * ({@link DebitTxn#of}, {@link CreditTxn#of}).
     */
    protected static void prepareAudit(WalletTxn txn, String vendorClassName, String vendorTxnId, long createdTimestamp) {
        txn.setVendorClassName(vendorClassName);
        txn.setVendorTxnId(vendorTxnId);
        txn.setGaTxnId(UuidUtil.newUuidV7String());
        txn.setCreatedTs(createdTimestamp);
        txn.setCreatedAt(DATE_TIME_FORMATTER.format(Instant.ofEpochMilli(createdTimestamp)));
    }

    /** Couchbase doc id of this txn. Each leaf builds it from {@code vendorClassName + KIND + vendorTxnId}. */
    @JsonIgnore
    public abstract String getId();

    /** Couchbase doc id of the {@link WalletRoundLedger} this txn belongs to. */
    @JsonIgnore
    public String getRoundDocId() {
        return vendorClassName + "::" + vendorPlayerUsername + "::" + vendorRoundId;
    }

    // --- Lifecycle helpers ---

    @JsonIgnore public boolean isSettled()          { return state == GameRoundState.SETTLED; }
    @JsonIgnore public boolean isUnsettled()        { return state == GameRoundState.UNSETTLED; }
    @JsonIgnore public boolean isRefunded()         { return state == GameRoundState.REFUNDED; }
    @JsonIgnore public boolean isSuccess()          { return status == TxnStatus.SUCCESS; }
    @JsonIgnore public boolean isError()            { return status == TxnStatus.ERROR; }
    @JsonIgnore public boolean isStillProcessing()  { return status == TxnStatus.SENT; }
}
